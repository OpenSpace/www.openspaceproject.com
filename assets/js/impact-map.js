// Embed mode (impact.html?embed): show only the map, filling the whole window to enable
// embedding of the map into another source. Set here, before the body renders, to avoid a
// flash of the full page. Combine with ?layer=orgs (or the legacy #orgs hash) to show the
// Organizations layer instead of startups
if (new URLSearchParams(window.location.search).has('embed')) {
  document.documentElement.classList.add('impact-embed');
}

document.addEventListener('DOMContentLoaded', () => {
  let loaded = false;
  function loadMapAssets() {
    if (loaded) {
      return;
    }
    loaded = true;

    // Startup locations as [{ lat, lng, total }], generated by the status page
    // (github.com/OpenSpace/status.openspaceproject.com, scripts/generate-data.ts)
    let leafletReady = false;
    let places = undefined;
    function tryInit() {
      if (leafletReady && places !== undefined) {
        initImpactMap(places);
      }
    }

    // Leaflet is vendored under assets/vendor/leaflet (see the download instructions in
    // that folder) so the map doesn't depend on unpkg at runtime. Keep the lazy load:
    // only fetch it when the map nears the viewport
    const js = document.createElement('script');
    js.src = '/assets/vendor/leaflet/leaflet.js';
    js.onload = () => {
      leafletReady = true;
      tryInit();
    };
    document.head.appendChild(js);

    // If the status data fails to load, don't hang forever waiting for it; init the map
    // anyway with no startup data so layers that don't depend on it (e.g. Organizations)
    // still work
    fetch('https://status.openspaceproject.com/places.json')
      .then((res) => {
        if (!res.ok) {
          throw new Error(`HTTP ${res.status}`);
        }
        return res.json();
      })
      .then((json) => { places = Array.isArray(json) ? json : []; })
      .catch((err) => {
        console.warn('Could not load startup locations:', err);
        places = [];
      })
      .finally(tryInit);
  }

  const mapEl = document.getElementById('page-impact-startup-map');
  if ('IntersectionObserver' in window && mapEl) {
    const obs = new IntersectionObserver((entries) => {
      if (entries[0].isIntersecting) {
        obs.disconnect();
        loadMapAssets();
      }
    }, { rootMargin: '300px' });
    obs.observe(mapEl);
  }
  else {
    loadMapAssets();
  }
});
